# Embed hackcard-web-ui/www into firmware as PROGMEM byte arrays (safe for JS/CSS)
$root = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$srcRoot = Join-Path $root "HackCard_ESP32\data\www"
$outDir = Join-Path $PSScriptRoot "..\src\apps\system"
$outH = Join-Path $outDir "WebUiEmbedded.h"
$outCpp = Join-Path $outDir "WebUiEmbedded.cpp"

if (-not (Test-Path $srcRoot)) {
  Write-Error "Missing $srcRoot - run sync-web-ui.ps1 first"
  exit 1
}

$files = @(
  @{ Key = "index_html"; Path = "index.html"; Mime = "text/html"; Uri = "/" },
  @{ Key = "profile_html"; Path = "profile.html"; Mime = "text/html"; Uri = "/profile.html" },
  @{ Key = "dashboard_css"; Path = "assets\css\dashboard.css"; Mime = "text/css"; Uri = "/assets/css/dashboard.css" },
  @{ Key = "profile_css"; Path = "assets\css\profile.css"; Mime = "text/css"; Uri = "/assets/css/profile.css" },
  @{ Key = "api_js"; Path = "assets\js\api.js"; Mime = "application/javascript"; Uri = "/assets/js/api.js" },
  @{ Key = "dashboard_js"; Path = "assets\js\dashboard.js"; Mime = "application/javascript"; Uri = "/assets/js/dashboard.js" },
  @{ Key = "profile_js"; Path = "assets\js\profile.js"; Mime = "application/javascript"; Uri = "/assets/js/profile.js" },
  @{ Key = "qrcode_js"; Path = "assets\js\qrcode.min.js"; Mime = "application/javascript"; Uri = "/assets/js/qrcode.min.js" }
)

function Format-ByteArray([byte[]]$bytes) {
  $lines = New-Object System.Collections.Generic.List[string]
  for ($i = 0; $i -lt $bytes.Length; $i += 16) {
    $end = [Math]::Min($i + 15, $bytes.Length - 1)
    $chunk = $bytes[$i..$end]
    $hex = ($chunk | ForEach-Object { "0x{0:X2}" -f $_ }) -join ", "
    $lines.Add("  $hex")
  }
  return ($lines -join ",`n")
}

$utf8NoBom = New-Object System.Text.UTF8Encoding $false

$h = @"
#pragma once

#include <Arduino.h>

struct WebUiEmbeddedFile {
  const char* uri;
  const char* mime;
  const uint8_t* data;
  size_t len;
};

extern const WebUiEmbeddedFile kWebUiFiles[];
extern const size_t kWebUiFileCount;
"@

$cpp = New-Object System.Text.StringBuilder
[void]$cpp.AppendLine("// Auto-generated by scripts/generate-embedded-ui.ps1 - do not edit")
[void]$cpp.AppendLine("#include ""WebUiEmbedded.h""")
[void]$cpp.AppendLine("")

foreach ($f in $files) {
  $full = Join-Path $srcRoot $f.Path
  if (-not (Test-Path $full)) {
    Write-Error "Missing file: $full"
    exit 1
  }
  $bytes = [IO.File]::ReadAllBytes($full)
  $arrayName = "kWebUiData_$($f.Key)"
  $lenName = "kWebUiLen_$($f.Key)"
  [void]$cpp.AppendLine("static const uint8_t $arrayName[] PROGMEM = {")
  [void]$cpp.AppendLine((Format-ByteArray $bytes))
  [void]$cpp.AppendLine("};")
  [void]$cpp.AppendLine("static const size_t $lenName = $($bytes.Length);")
  [void]$cpp.AppendLine("")
}

[void]$cpp.AppendLine("const WebUiEmbeddedFile kWebUiFiles[] = {")
foreach ($f in $files) {
  [void]$cpp.AppendLine("  { `"$($f.Uri)`", `"$($f.Mime)`", kWebUiData_$($f.Key), kWebUiLen_$($f.Key) },")
}
[void]$cpp.AppendLine("};")
[void]$cpp.AppendLine("const size_t kWebUiFileCount = sizeof(kWebUiFiles) / sizeof(kWebUiFiles[0]);")
[void]$cpp.AppendLine("")

[System.IO.File]::WriteAllText($outH, $h, $utf8NoBom)
[System.IO.File]::WriteAllText($outCpp, $cpp.ToString(), $utf8NoBom)
Write-Host "Generated $outH and $outCpp"
